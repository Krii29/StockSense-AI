import { useEffect, useState } from 'react';
import { fetchStockPrediction } from '../../services/api';

const TREND_STYLES = {
  bullish: 'text-emerald-300 border-emerald-400/30 bg-emerald-400/10',
  bearish: 'text-rose-300 border-rose-400/30 bg-rose-400/10',
  neutral: 'text-slate-300 border-slate-400/30 bg-slate-400/10',
};

export default function AIPrediction({ symbol, market }) {
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');

  useEffect(() => {
    let cancelled = false;

    const loadPrediction = async () => {
      setLoading(true);
      setError('');
      setData(null);
      try {
        const result = await fetchStockPrediction(symbol, market, 5);
        if (!cancelled) setData(result);
      } catch {
        if (!cancelled) setError('Not enough historical data to generate a forecast for this symbol yet.');
      } finally {
        if (!cancelled) setLoading(false);
      }
    };

    if (symbol) loadPrediction();
    return () => {
      cancelled = true;
    };
  }, [symbol, market]);

  return (
    <div className="p-6 bg-slate-900/80 border border-cyan-400/15 rounded-2xl shadow-lg shadow-slate-950/20">
      <div className="flex items-center justify-between mb-4">
        <h3 className="font-bold text-white flex items-center gap-2">
          <span>🔮</span> AI Price Forecast (LSTM)
        </h3>
        {data && (
          <span className={`text-xs font-bold px-2.5 py-1 rounded-full border capitalize ${TREND_STYLES[data.trend] || TREND_STYLES.neutral}`}>
            {data.trend}
          </span>
        )}
      </div>

      {loading && (
        <p className="text-xs text-slate-500">
          Training model and generating forecast… this can take up to a minute the first time for a new symbol.
        </p>
      )}
      {error && <p className="text-xs text-rose-300">{error}</p>}

      {data && (
        <>
          <div className="grid grid-cols-2 gap-4 mb-4">
            <div>
              <p className="text-xs text-slate-400">Last Close</p>
              <p className="text-lg font-bold text-white">₹{data.last_close?.toLocaleString()}</p>
            </div>
            <div>
              <p className="text-xs text-slate-400">Est. Volatility (60d)</p>
              <p className="text-lg font-bold text-white">{data.volatility_pct}%</p>
            </div>
          </div>

          <p className="text-xs text-slate-400 mb-2">Next {data.forecast.length} trading days (predicted close)</p>
          <div className="flex flex-wrap gap-2">
            {data.forecast.map((price, i) => (
              <div key={i} className="px-3 py-2 rounded-xl bg-slate-950/60 border border-slate-800 text-center min-w-[72px]">
                <p className="text-[10px] text-slate-500">Day {i + 1}</p>
                <p className="text-sm font-semibold text-white">₹{price.toLocaleString()}</p>
              </div>
            ))}
          </div>

          <p className="text-[11px] text-slate-500 mt-4">
            Generated by an LSTM neural network trained on this symbol's historical closing prices. Educational forecast only — not investment advice.
          </p>
        </>
      )}
    </div>
  );
}